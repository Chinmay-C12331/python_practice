n=int(input())
thousand = int(n/1000)
f_hund = int((n-(1000*thousand))/500)
hund = int((n-(1000*thousand)-(500*f_hund))/100)
fifty = int((n-(1000*thousand)-(500*f_hund)-(100*hund))/50)
twenty = int((n-(1000*thousand)-(500*f_hund)-(100*hund)-(50*fifty))/20)
five = int((n-(1000*thousand)-(500*f_hund)-(100*hund)-(50*fifty)-(20*twenty))/5)
one = int((n-(1000*thousand)-(500*f_hund)-(100*hund)-(50*fifty)-(20*twenty)-(5*five))/1)
print("1000:"+str(thousand))
print("500:"+str(f_hund))
print("100:"+str(hund))
print("50:"+str(fifty))
print("20:"+str(twenty))
print("5:"+str(five))
print("1:"+str(one))
